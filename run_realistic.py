# detailed explanation
# the real-map illustration (see src/realistic.py for what is real and what is
# assumed). it runs the same pieces as the main project on the 25 largest
# US metro areas and 8 candidate hubs:
#   - the fair capacity-aware baseline, the lp, and the milp choice of hubs
#   - a sweep of the opening cost, to show how the chosen hubs change
#
# it writes figures/realistic_map.png and results/REALISTIC.md.
# every number comes from the code. the opening cost and shipping rate are
# assumptions in made-up dollars, so read the pattern, not the dollar amounts.
#
# run it with: python run_realistic.py
from pathlib import Path

from src.baseline import capacity_aware_plan, transport_cost
from src.lp_model import solve_transportation
from src.milp_model import fixed_cost_sweep, solve_facility_location
from src import plots
from src.realistic import build_realistic_instance

ROOT = Path(__file__).parent
(ROOT / "figures").mkdir(exist_ok=True)
(ROOT / "results").mkdir(exist_ok=True)

inst = build_realistic_instance()
base_fixed = next(iter(inst.fixed_cost.values()))
total_demand = sum(inst.demand.values())

fair_cost = transport_cost(inst, capacity_aware_plan(inst))
lp = solve_transportation(inst)
all_open_total = lp.cost + sum(inst.fixed_cost.values())
milp = solve_facility_location(inst)

plots.plot_realistic_map(inst, milp, ROOT / "figures" / "realistic_map.png")

multipliers = [0.25, 0.5, 1, 2, 4]
sweep = fixed_cost_sweep(inst, multipliers)

lines = []
add = lines.append
add("# Real-map illustration")
add("")
add("Generated by `run_realistic.py`. This is an illustration, not company data.")
add("")
add(f"- {len(inst.regions)} customer regions: the largest US metro areas, demand = 2020 population / 100,000 "
    f"({total_demand:,.0f} units in total).")
add(f"- {len(inst.warehouses)} candidate hubs picked by us, each with capacity {next(iter(inst.capacity.values())):,.0f} "
    f"units ({100 * next(iter(inst.capacity.values())) / total_demand:.0f}% of demand) and an assumed opening cost of "
    f"{base_fixed:,.0f} (made-up dollars). Shipping rate {inst.rate} per unit per km, great-circle distances.")
add("")
add("| Plan | Cost |")
add("|---|---:|")
add(f"| Fair baseline, all hubs open (shipping) | {fair_cost:,.0f} |")
add(f"| LP, all hubs open (shipping) | {lp.cost:,.0f} |")
add(f"| LP, all hubs open (shipping + opening) | {all_open_total:,.0f} |")
add(f"| MILP chooses hubs (shipping + opening) | {milp.total_cost:,.0f} |")
add("")
add(f"- LP saves {100 * (fair_cost - lp.cost) / fair_cost:.1f}% of shipping versus the fair baseline.")
add(f"- MILP opens {len(milp.open_warehouses)} of {len(inst.warehouses)} hubs: {', '.join(milp.open_warehouses)}. "
    f"It saves {100 * (all_open_total - milp.total_cost) / all_open_total:.1f}% of total cost versus opening all.")
add("")
add("| Opening-cost multiplier | Hubs open | Which |")
add("|---:|---:|---|")
for m, sol in sweep:
    add(f"| {m:g} | {len(sol.open_warehouses)} | {', '.join(sol.open_warehouses)} |")
add("")
add("The default opening cost was chosen up front, but a few values were tried before settling on it, so "
    "treat the sweep as the honest picture of how much the hub choice depends on it.")
add("The LP saves little over the fair baseline here because capacity is generous (2x demand overall), so "
    "'nearest hub with room left' is already close to optimal. Savings depend on how tight capacity is.")

(ROOT / "results" / "REALISTIC.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines))
